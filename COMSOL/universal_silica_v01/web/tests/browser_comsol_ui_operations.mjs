/** COMSOL-style UI and Geometry operations browser regression. */
import assert from "node:assert/strict";
import {createRequire} from "node:module";
const {chromium}=createRequire(import.meta.url)("playwright");
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--disable-dev-shm-usage"]});
try{
 const page=await browser.newPage({viewport:{width:1440,height:850}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto(process.env.TEST_BASE_URL||"http://127.0.0.1:8765/COMSOL/universal_silica_v01/web/",{waitUntil:"load"});
 await page.waitForSelector("#ls-cad-root-settings",{state:"attached"});
 const root=page.locator('summary[data-action="geometry"]');
 await root.click();
 assert.equal(await page.locator("#ls-cad-root-settings").isVisible(),true);
 assert.equal(await root.locator("..").getAttribute("open"),"");
 assert.ok((await page.locator("#ls-cad-root-sequence").textContent()).includes("Circle 2"));
 await page.locator('[data-cad-node="c2"]').click();
 assert.equal(await page.locator("#ls-cad-radius").inputValue(),"d/2");
 await page.locator("#ls-cad-add-circle").click();
 assert.equal(await page.locator("#ls-cad-radius").inputValue(),"2.5[um]");
 await page.locator("#ls-cad-y").fill("5[um]");
 assert.equal(await page.locator("#ls-cad-y").inputValue(),"5[um]");
 await page.locator("#ls-cad-undo").click();
 assert.equal(await page.locator("#ls-cad-y").inputValue(),"0[um]");
 await page.locator("#ls-cad-redo").click();
 assert.equal(await page.locator("#ls-cad-y").inputValue(),"5[um]");
 await page.locator('[data-cad-node="c3"]').click({button:"right"});
 await page.locator('#ls-cad-menu [data-cmd="copy"]').click();
 await page.locator('[data-cad-node="c3"]').click({button:"right"});
 await page.locator('#ls-cad-menu [data-cmd="paste"]').click();
 assert.equal(await page.locator('[data-cad-node="c4"]').count(),1);
 await page.locator("#ls-cad-undo").click();
 assert.equal(await page.locator('[data-cad-node="c4"]').count(),0);
 await page.locator("#ls-cad-object-select").selectOption("c1");
 assert.equal(await page.locator("#ls-cad-radius").inputValue(),"rb");
 const view=page.locator("#ls-cad-view"),box=await view.boundingBox();
 assert.ok(box&&box.width>300&&box.height>150);
 const before=Number(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle').first().getAttribute("cx"));
 await page.mouse.move(box.x+15,box.y+60);await page.mouse.down();await page.mouse.move(box.x+60,box.y+75,{steps:5});await page.mouse.up();
 const after=Number(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle').first().getAttribute("cx"));
 assert.ok(after>before+10,"Pan by dragging background");
 await view.hover({position:{x:25,y:25}});await page.mouse.wheel(0,-100);
 assert.ok((await page.locator("#ls-cad-legend").textContent()).includes("Zoom 115%"));
 await page.locator("#ls-cad-fit").click();
 assert.ok((await page.locator("#ls-cad-legend").textContent()).includes("Zoom 100%"));
 await page.locator("#ls-cad-object-select").selectOption("root");
 assert.equal(await page.locator("#ls-cad-root-settings").isVisible(),true);
 await page.locator("#ls-cad-root-unit").selectOption("nm");
 assert.ok((await page.locator("#ls-cad-legend").textContent()).includes("nm"));
 await page.locator('[data-tab="geometry"]').click();
 await page.locator('#ls-ribbon-tools [data-action="cadBuildAll"]').click();
 assert.ok((await page.locator("#ls-cad-status").textContent()).includes("Built"));
 await page.screenshot({path:"/tmp/ls_comsol_ui_operations.png"});
 await page.locator("#ls-cad-close").click();
 await page.locator("#calculateBtn").click();
 await page.waitForFunction(()=>Number(document.querySelector("#neff")?.textContent)>1.4);
 assert.deepEqual(errors,[]);
 console.log("PASS: COMSOL-like Geometry root, circle edit, undo/redo, context copy/paste, Graphics pan/zoom, Build All and FEM");
}finally{await browser.close();}
