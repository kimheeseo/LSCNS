/** Browser regression: parameter radius, nested layers, hover, duplication and delete confirmation. */
import assert from "node:assert/strict";
import {createRequire} from "node:module";
import {fileURLToPath} from "node:url";
import path from "node:path";
const {chromium}=createRequire(import.meta.url)("playwright");
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--disable-dev-shm-usage"]});
try{
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.goto(process.env.TEST_BASE_URL||"http://127.0.0.1:8765/COMSOL/universal_silica_v01/web/",{waitUntil:"load",timeout:90000});
 await page.locator('[data-dimension="2D"]').click();
 await page.locator('[data-interface="ewfd"]').click();
 await page.locator('[data-wizard="add"]').click();
 await page.locator('[data-wizard="select-added"]').click();
 await page.locator('[data-wizard="study"]').click();
 await page.locator('[data-study="mode"]').first().click();
 await page.locator('[data-wizard="done"]').click();
 await page.locator('.ls-model-tree [data-action="settings"]').click();
 const sample=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../examples/COMSOL_microstructured_parameters.txt");
 await page.locator("#ls-params-file").setInputFiles(sample);
 await page.waitForFunction(()=>document.querySelectorAll("#ls-parameter-rows tr").length===10,{timeout:10000});
 const rbRow=page.locator("#ls-parameter-rows tr").nth(3);
 assert.equal(await rbRow.locator('[data-field="name"]').inputValue(),"rb");
 await page.locator('summary[data-action="geometry"]').click({button:"right"});
 await page.locator('#ls-cad-menu > ul > li > [data-cmd="circle"]').click();
 await page.locator("#ls-cad-radius").fill("rb+wlr");
 await page.locator("#ls-cad-build-selected").click();
 const shape=page.locator('#ls-cad-view [data-cad-shape="c1"]');
 assert.equal(await shape.count(),1);
 assert.ok((await page.locator("#ls-cad-legend").textContent()).includes("1 object"));
 const basePixelRadius=Number(await shape.locator(".ls-cad-rendered-surface circle").getAttribute("r"));
 assert.ok(basePixelRadius>25,"Base circle should occupy visible graphics area after Build");
 await page.locator("#ls-cad-radius").fill("rb+wlr/2");
 const smallerPixelRadius=Number(await shape.locator(".ls-cad-rendered-surface circle").getAttribute("r"));
 assert.ok(smallerPixelRadius<basePixelRadius*.97,"Radius edit must shrink the actual pixel circle, not merely rescale viewport");
 await page.locator("#ls-cad-radius").fill("rb+wlr");
 const restoredPixelRadius=Number(await shape.locator(".ls-cad-rendered-surface circle").getAttribute("r"));
 assert.ok(Math.abs(restoredPixelRadius-basePixelRadius)<.01,"Restore radius should restore actual SVG radius");
 const initialRadius=await shape.locator("title").textContent();
 assert.ok(initialRadius.includes("Radius")&&initialRadius.includes("µm"),initialRadius);
 await page.screenshot({path:"/tmp/comsol_circle_radius_build.png"});
 const surface=shape.locator(".ls-cad-rendered-surface");
 const before=await surface.evaluate(el=>getComputedStyle(el).fill);
 await shape.locator("circle").first().hover({force:true});
 await page.waitForFunction(()=>{const el=document.querySelector('#ls-cad-view [data-cad-shape="c1"] .ls-cad-rendered-surface');return el&&getComputedStyle(el).fill==="rgb(238, 167, 163)";},{timeout:5000});
 const hover=await surface.evaluate(el=>getComputedStyle(el).fill);
 assert.notEqual(hover,before,"Hover should change Circle from gray to red");
 await page.screenshot({path:"/tmp/comsol_circle_hover_red.png"});
 await page.locator("#ls-cad-layers-section summary").click();
 await page.locator("#ls-cad-layer").fill("wlr");
 await page.locator("#ls-cad-build-selected").click();
 assert.equal(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle.ls-cad-layer-boundary').count(),1);
 assert.equal(await page.locator('#ls-cad-view [data-cad-shape="c1"] line.ls-cad-layer-boundary').count(),4);
 const inner1=Number(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle.ls-cad-layer-boundary').getAttribute("r"));
 assert.equal(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle.ls-cad-layer-region').count(),1);
 await page.locator("#ls-cad-layer").fill("wlr/2");
 const thinnerInner=Number(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle.ls-cad-layer-boundary').getAttribute("r"));
 assert.ok(thinnerInner>inner1*1.04,"Smaller Layer thickness must enlarge inner domain in actual SVG");
 await page.locator("#ls-cad-layer").fill("wlr");
 const restoredInner=Number(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle.ls-cad-layer-boundary').getAttribute("r"));
 assert.ok(Math.abs(restoredInner-inner1)<.01,"Layer thickness restoration should restore original inner radius");
 await page.locator("#ls-cad-add-layer").click();
 assert.equal(await page.locator('#ls-cad-extra-layers input').count(),1);
 await page.locator('#ls-cad-extra-layers input').fill("wlr/2");
 await page.locator("#ls-cad-build-selected").click();
 assert.equal(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle.ls-cad-layer-boundary').count(),2);
 const inner2=Number(await page.locator('#ls-cad-view [data-cad-shape="c1"] circle.ls-cad-layer-boundary').last().getAttribute("r"));
 assert.ok(inner2<inner1,"Second layer should create a smaller radius");
 await page.screenshot({path:"/tmp/comsol_circle_multi_layer.png"});
 await page.locator('.ls-model-tree [data-cad-node="c1"]').click({button:"right"});
 await page.locator('#ls-cad-menu > ul > li > [data-cmd="duplicate"]').click();
 assert.equal(await page.locator('[data-cad-node="c2"]').count(),1);
 assert.equal(await page.locator("#ls-cad-radius").inputValue(),"rb+wlr");
 assert.equal(await page.locator("#ls-cad-layer").inputValue(),"wlr");
 assert.equal(await page.locator('#ls-cad-extra-layers input').inputValue(),"wlr/2");
 await page.locator('[data-cad-node="c2"]').click({button:"right"});
 await page.locator('#ls-cad-menu > ul > li > [data-cmd="delete"]').click();
 assert.ok(await page.locator("#ls-cad-delete-dialog").isVisible());
 assert.ok((await page.locator("#ls-cad-delete-message").textContent()).includes("Circle 2"));
 await page.locator(".ls-cad-confirm-no").click();
 assert.equal(await page.locator('[data-cad-node="c2"]').count(),1,"No must cancel deletion");
 await page.locator('[data-cad-node="c2"]').click({button:"right"});
 await page.locator('#ls-cad-menu > ul > li > [data-cmd="delete"]').click();
 await page.locator(".ls-cad-confirm-yes").click();
 await page.waitForFunction(()=>!document.querySelector('[data-cad-node="c2"]'));
 assert.equal(await page.locator('[data-cad-node="c1"]').count(),1);
 await page.screenshot({path:"/tmp/comsol_circle_duplicate_delete.png"});
 await page.locator('.ls-model-tree [data-action="settings"]').click();
 await rbRow.locator('[data-field="expression"]').fill("45[um]");
 await page.locator('[data-cad-node="c1"]').click();
 const changedRadius=await page.locator('#ls-cad-view [data-cad-shape="c1"] title').textContent();
 assert.notEqual(changedRadius,initialRadius,"Parameters edits must update Geometry expressions");
 const changedPixelRadius=Number(await page.locator('#ls-cad-view [data-cad-shape="c1"] .ls-cad-rendered-surface circle').getAttribute("r"));
 assert.ok(changedPixelRadius>basePixelRadius*1.03,"Changing global rb must increase SVG radius on locked physical viewport");
 await page.locator('[data-tab="home"]').click();
 assert.ok(await page.locator('#ls-ribbon-tools [data-action="cadBuildAll"]').isVisible());
 assert.ok(await page.locator('#ls-ribbon-tools [data-action="wavePhysics"]').isVisible());
 assert.deepEqual(errors,[],"No browser JavaScript errors");
 console.log("PASS: fixed-scale radius pixel growth/shrink, parameter-driven SVG circle size, layer thickness-driven inner radius, gray/red hover, duplicate/delete");
}finally{await browser.close();}
