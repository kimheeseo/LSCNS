import assert from 'node:assert/strict';
import {volumeFromBpm,buildFiberWireframe,scanRingFromWireframe,VIEWER_VERSION} from '../fiber_3d_webgl.mjs';
const N=32,axis=Array.from({length:N},(_,i)=>i-N/2),slices=Array.from({length:9},(_,k)=>({z_um:k*10,intensity:axis.flatMap(y=>axis.map(x=>Math.exp(-(x*x+y*y)/(4+k))))}));
const data={config:{length_um:80},grid:N,axis_um:axis,slices};
const vol=volumeFromBpm(data);assert.ok(vol.pointCount>100);assert.equal(vol.points.length,vol.pointCount*7);assert.ok(vol.points.every(x=>Number.isFinite(x)));assert.ok(vol.points[2]>=-2.6&&vol.points[2]<=2.6);
assert.throws(()=>volumeFromBpm({grid:N,axis_um:axis,slices:[{z_um:0,intensity:[1]}]}),/Invalid BPM/);
const solid=buildFiberWireframe({profile:'step',coreRadiusUm:5.5});assert.ok(solid.lineCount>100);assert.equal(solid.lines.length,solid.lineCount*14);
const hcf=buildFiberWireframe({profile:'hcf',hcfGeometry:{coreRadiusUm:16,extentUm:50,rings:[{layers:[{x:25,y:0,radius:8,wall:0.6,level:1}]}]}});assert.ok(hcf.lineCount>solid.lineCount/2);
const movingRing=scanRingFromWireframe(solid);
assert.ok(movingRing.lineCount>50,'scan ring should use real front-end geometry');
assert.equal(movingRing.lines.length,movingRing.lineCount*14);
for(let i=0;i<movingRing.lines.length;i+=7)assert.equal(movingRing.lines[i+2],0);
const hcfScan=scanRingFromWireframe(hcf);
assert.ok(hcfScan.lineCount>movingRing.lineCount/2);
assert.equal(VIEWER_VERSION,'1.1.0');
import {readFileSync} from 'node:fs';
const gui=readFileSync(new URL('../fiber_3d_ui.mjs',import.meta.url),'utf8');
const renderer=readFileSync(new URL('../fiber_3d_webgl.mjs',import.meta.url),'utf8');
assert.match(gui,/requestAnimationFrame\(animate\)/);
assert.match(gui,/if\(data\)startPlayback\(\)/);
assert.match(gui,/id="f3-speed"/);
assert.doesNotMatch(gui,/setInterval\(/);
assert.match(renderer,/setPlayhead\(fraction,animated=true\)/);
assert.match(renderer,/uPulseOn/);
assert.match(renderer,/uCursor/);
console.log('PASS: 3D BPM point samples, moving scan ring, continuous playback wiring, input guards, version');
