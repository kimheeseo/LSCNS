// STEP19 — repository-wide protection and linkage checks.
// Run: node --test DCI/DataCenter/ls3d-three/step19.contract.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,readdirSync,existsSync} from 'node:fs';
import {join,resolve,dirname} from 'node:path';
import {createHash} from 'node:crypto';

const root=process.cwd();
const home=join(root,'DCI/DataCenter');
const three=join(home,'ls3d-three');
const html=readFileSync(join(home,'LS_Datacenter_3D.html'),'utf8');
function gitBlobSha(text){
  const buffer=Buffer.from(text,'utf8'),header=Buffer.from('blob '+buffer.byteLength+'\0');
  return createHash('sha1').update(header).update(buffer).digest('hex');
}

test('preserve original 2D Gold Pixel Tour and BOM entrypoints',()=>{
  const campus='LS_Datacenter_Campus.html';
  assert.equal(gitBlobSha(readFileSync(join(home,campus),'utf8')),
    '9c84f24f2101043d7c113ce2d0da50e7245bc318','protected original modified: '+campus);
  const bom=readFileSync(join(home,'index.html'),'utf8');
  for(const marker of ['id="trunkFiberCount"','engineering-v82.js?v=',
    'engineering-v82-ui.js?v=','id="run"'])
    assert.ok(bom.includes(marker),'missing BOM entrypoint: '+marker);
});
test('all seven geographic modes and critical security/rack/network/colo assets remain present',()=>{
  const zones=['campus','utility','cooling','gray','hall','network','ops'];
  for(const id of zones)assert.match(html,new RegExp("id:'"+id+"'"),'missing zone '+id);
  for(const id of ['entry-desk','xray','metal-detector','gate',
    'gpu-0-0','tor-a','colo','colo-rack-a','colo-rack-b','colo-rack-c',
    'carrier','mmr','odf','core','crah-a','tower-a','ups-a']){
    // GPU-0-0 is generated by a bounded for-loop; assert its template.
    if(id==='gpu-0-0')assert.match(html,/addAsset\('hall',`gpu-\$\{r\}-\$\{i\}`/);
    else assert.ok(html.includes("'"+id+"'"),'missing asset '+id);
  }
});
test('Three.js revision and latest rack controls browser bootstrap path are pinned',()=>{
  assert.match(html,/three@0\.186\.1\/build\/three\.module\.js/);
  assert.match(html,/ls3d-three\/bootstrap\.mjs\?v=20261031-navigation-v1/);
  const bootstrap=readFileSync(join(three,'bootstrap.mjs'),'utf8');
  assert.match(bootstrap,/scene-adapter\.mjs\?v=20261029-staging-workshop-v1/);
});
test('all ls3d-three relative ES imports exist in repository (no broken graph)',()=>{
  const files=readdirSync(three).filter(name=>name.endsWith('.mjs'));
  assert.ok(files.length>=18);
  for(const file of files){
    const full=join(three,file),src=readFileSync(full,'utf8');
    for(const match of src.matchAll(/(?:import|from)\s*(?:[^'"\n]*?from\s*)?['"](\.\/?[^'"]+)['"]/g)){
      const relative=match[1].split('?')[0];
      assert.ok(existsSync(resolve(dirname(full),relative)),file+' imports missing '+relative);
    }
  }
});
test('stage19 browser suite has screenshot, diagnostic and FPS evidence hooks',()=>{
  const src=readFileSync(join(three,'step19.integration.spec.mjs'),'utf8');
  assert.match(src,/step19-zone-/);
  assert.match(src,/mmr-colo-mep\.json/);
  assert.match(src,/chromium-performance-90-frames\.json/);
  assert.match(src,/pageerror/);
  assert.match(src,/engine=three/);
});

